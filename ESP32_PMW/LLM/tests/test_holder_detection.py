"""Synthetic image regressions, not physical print or camera acceptance tests."""
import json
import unittest

import cv2
import numpy as np

from LLM.analyse.holder_detection import detect_checker_centers, detect_labeled_centers


def checker_image(*, size=320, center=(160, 160), angle_deg=0, scale=1,
                  projective=False, noise=0, blur=0):
    """Render an independent piecewise-constant CAD-like 2×2 checker."""
    source = np.full((161, 161), 25, np.uint8)
    source[40:80, 40:80] = 235
    source[80:120, 80:120] = 235
    source_center = np.array([79.5, 79.5], np.float32)
    affine = cv2.getRotationMatrix2D(tuple(source_center), angle_deg, scale)
    affine[:, 2] += np.asarray(center) - source_center
    transform = np.vstack([affine, [0., 0., 1.]])
    if projective:
        # Oblique local axes plus depth-dependent magnification, not simply a
        # rotated template generated by the detector's own sampling function.
        skew = np.array([[.77, .28, -10], [.05, 1., 2], [.0008, -.0006, 1.]])
        transform = skew @ transform
    image = cv2.warpPerspective(source, transform, (size, size), borderValue=25)
    truth = cv2.perspectiveTransform(source_center.reshape(1, 1, 2), transform).reshape(2)
    if blur:
        image = cv2.GaussianBlur(image, (0, 0), blur)
    if noise:
        rng = np.random.default_rng(42)
        image = np.clip(image.astype(float) + rng.normal(0, noise, image.shape), 0, 255).astype(np.uint8)
    return image, truth


class HolderDetectionTests(unittest.TestCase):
    def test_rotated_and_projected_centers(self):
        for angle in (0, 17, 45, 79, 126, 180, 271):
            for projective in (False, True):
                with self.subTest(angle=angle, projective=projective):
                    image, truth = checker_image(angle_deg=angle, projective=projective)
                    detected = detect_checker_centers(image)
                    self.assertEqual(len(detected), 1)
                    self.assertLess(np.linalg.norm(detected[0]["center_px"] - truth), .7)
                    self.assertGreaterEqual(len(detected[0]["radii_px"]), 2)
                    self.assertNotIn("id", detected[0])
                    json.dumps(detected, allow_nan=False)

    def test_blur_noise_and_small_target(self):
        for scale, blur, noise in ((1, 1.3, 5), (.35, .7, 3), (.22, .5, 2)):
            with self.subTest(scale=scale):
                image, truth = checker_image(angle_deg=31, scale=scale, blur=blur, noise=noise)
                detected = detect_checker_centers(cv2.cvtColor(image, cv2.COLOR_GRAY2BGR))
                self.assertEqual(len(detected), 1)
                self.assertLess(np.linalg.norm(detected[0]["center_px"] - truth), .8)

    def test_no_outer_corners_dots_or_straight_edges(self):
        image = np.full((320, 480), 25, np.uint8)
        cv2.rectangle(image, (30, 30), (100, 100), 235, -1)
        cv2.circle(image, (210, 70), 15, 235, -1)
        cv2.line(image, (300, 40), (400, 140), 235, 8)
        cv2.rectangle(image, (20, 230), (460, 280), 235, -1)
        self.assertEqual(detect_checker_centers(image), [])
        self.assertEqual(detect_checker_centers(np.full((100, 100), 255, np.uint8)), [])

    def test_partial_occlusion_does_not_create_a_center(self):
        image, _ = checker_image()
        image[120:200, 120:160] = 25
        self.assertEqual(detect_checker_centers(image), [])

    def test_roi_coordinates_and_ambiguity(self):
        image1, truth1 = checker_image(center=(90, 160))
        image2, truth2 = checker_image(center=(235, 160), angle_deg=31)
        image = np.maximum(image1, image2)
        result = detect_labeled_centers(image, {
            "P1": [40, 110, 100, 100], "P2": [185, 110, 100, 100],
            "both": [20, 90, 280, 140], "empty": [10, 10, 50, 50]})
        self.assertEqual(result["P1"]["status"], "detected")
        self.assertEqual(result["P2"]["status"], "detected")
        np.testing.assert_allclose(result["P1"]["center_px"], truth1, atol=.5)
        np.testing.assert_allclose(result["P2"]["center_px"], truth2, atol=.5)
        self.assertEqual(result["both"]["status"], "ambiguous")
        self.assertEqual(len(result["both"]["candidates"]), 2)
        self.assertNotIn("center_px", result["both"])
        self.assertEqual(result["empty"]["status"], "missing")
        self.assertNotIn("center_px", result["empty"])
        duplicate = detect_labeled_centers(image, {"P1": [40, 110, 100, 100], "P2": [45, 115, 90, 90]})
        self.assertTrue(all(r["status"] == "ambiguous" for r in duplicate.values()))
        self.assertTrue(all("center_px" not in r for r in duplicate.values()))

    def test_bad_inputs_and_borders(self):
        image, _ = checker_image()
        for roi in ([-1, 0, 30, 30], [0, 0, 0, 20], [300, 0, 30, 20],
                    [0., 0., 30.5, 20.], [0, 0, float("nan"), 20], [0, 0, 20]):
            with self.subTest(roi=roi), self.assertRaises(ValueError):
                detect_checker_centers(image, roi=roi)
        for options in ({"min_radius_support": 1}, {"radii_px": [3, 3]},
                        {"min_contrast": float("nan")}, {"max_candidates": 0},
                        {"min_distance_px": 0}):
            with self.subTest(options=options), self.assertRaises(ValueError):
                detect_checker_centers(image, **options)
        with self.assertRaises(ValueError):
            detect_checker_centers(image.astype(float))
        with self.assertRaises(ValueError):
            detect_labeled_centers(image, {"P1": None})
        self.assertEqual(detect_checker_centers(image, roi=[155, 155, 10, 10]), [])
        # A center outside the ROI is never allowed to enter after refinement.
        self.assertEqual(detect_checker_centers(image, roi=[0, 0, 158, 158]), [])


if __name__ == "__main__":
    unittest.main()
